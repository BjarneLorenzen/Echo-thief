export const LANG_IDS = Object.keys(LANGS);

/** Best match for the device's preferred languages, falling back to English. */
export function detectLang() {
  const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en']);
  for (const tag of prefs) {
    let code = String(tag).toLowerCase().split('-')[0];
    if (code === 'no' || code === 'nn') code = 'nb';
    if (LANGS[code]) return code;
  }
  return 'en';
}

let current = 'en';
let numberFmt = new Intl.NumberFormat('en', { minimumFractionDigits: 1, maximumFractionDigits: 1 });

/** Set the language: a code from LANGS, or 'auto' for the device language. Returns the code in use. */
export function setLang(choice) {
  current = choice === 'auto' || !LANGS[choice] ? detectLang() : choice;
  try { numberFmt = new Intl.NumberFormat(current, { minimumFractionDigits: 1, maximumFractionDigits: 1 }); } catch { /* keep previous */ }
  document.documentElement.lang = current;
  return current;
}

export function t(key) {
  const s = LANGS[current][key];
  return s !== undefined ? s : en[key] !== undefined ? en[key] : key;
}

/** Number with one decimal in the current locale (12.4 / 12,4). */
export function fmt1(n) {
  return numberFmt.format(n);
}

/** Translate everything in the DOM marked with data-i18n / data-i18n-html / data-i18n-aria. */
export function applyDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
    if (el.hasAttribute('title')) el.title = t(el.dataset.i18nAria);
  }
}
